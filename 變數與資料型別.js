// 用 typeof 得知「變數型別」

let num = 1;
let string = 'hello';
let phoneNum = '081235678'

console.log(typeof num);       // 印出「number」
console.log(typeof string);    // 印出「string」
console.log(typeof phoneNum);  // 印出「string」
